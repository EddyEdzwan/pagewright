// Build the installable web (iPhone home-screen) version into web-dist/.
// Same source as the desktop app; host-web.js stands in for Electron.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, 'web-dist');

// Everything the renderer loads at runtime (relative to the project root).
const COPY = [
  'src/index.html', 'src/styles.css', 'src/app.js', 'src/icons.js', 'src/objects.js', 'src/pdfops.js', 'src/tools.js', 'src/ui.js', 'src/host-web.js', 'src/third-party-licenses.txt',
  'node_modules/pdfjs-dist/build/pdf.mjs', 'node_modules/pdfjs-dist/build/pdf.worker.mjs',
  'node_modules/pdfjs-dist/cmaps', 'node_modules/pdfjs-dist/standard_fonts',
  'node_modules/pdfjs-dist/web/pdf_viewer.css', 'node_modules/pdfjs-dist/web/images',
  'node_modules/pdf-lib/dist/pdf-lib.min.js',
  'node_modules/@pdf-lib/fontkit/dist/fontkit.umd.min.js',
  'node_modules/tesseract.js/dist/tesseract.min.js', 'node_modules/tesseract.js/dist/worker.min.js',
  'node_modules/tesseract.js-core/tesseract-core-simd-lstm.wasm.js', 'node_modules/tesseract.js-core/tesseract-core-lstm.wasm.js',
  'node_modules/@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz',
];

fs.rmSync(OUT, { recursive: true, force: true });
fs.cpSync(path.join(ROOT, 'LICENSE'), path.join(OUT, 'LICENSE'));
for (const rel of COPY) {
  const src = path.join(ROOT, rel);
  if (!fs.existsSync(src)) throw new Error(`missing ${rel}`);
  fs.cpSync(src, path.join(OUT, rel), { recursive: true });
}

// Home-screen icons from the desktop icon artwork (macOS `sips`).
fs.mkdirSync(path.join(OUT, 'icons'), { recursive: true });
for (const [name, size] of [['apple-touch-icon.png', 180], ['icon-192.png', 192], ['icon-512.png', 512]]) {
  execFileSync('sips', ['-z', String(size), String(size), path.join(ROOT, 'build/icon.png'), '--out', path.join(OUT, 'icons', name)], { stdio: 'ignore' });
}

fs.writeFileSync(path.join(OUT, 'manifest.webmanifest'), JSON.stringify({
  name: 'Pagewright', short_name: 'Pagewright', description: 'Read, annotate, edit, sign and organise PDFs — offline, on device.',
  start_url: 'src/index.html', scope: './', display: 'standalone', orientation: 'any',
  background_color: '#24272e', theme_color: '#24272e',
  icons: [
    { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
  ],
}, null, 2));

fs.writeFileSync(path.join(OUT, 'index.html'),
  '<!doctype html><meta charset="utf-8"><title>Pagewright</title><meta http-equiv="refresh" content="0; url=src/index.html"><script>location.replace("src/index.html")</script>\n');

// Offline: precache every file; the cache name changes whenever any file changes.
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p); else files.push(path.relative(OUT, p).split(path.sep).join('/'));
  }
})(OUT);
const hash = crypto.createHash('sha256');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(OUT, f)));
const version = hash.digest('hex').slice(0, 12);

fs.writeFileSync(path.join(OUT, 'sw.js'), `// Generated by scripts/build-web.mjs — offline cache for Pagewright.
const CACHE = 'pagewright-${version}';
const FILES = ${JSON.stringify(['./', ...files])};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`);

const bytes = files.reduce((a, f) => a + fs.statSync(path.join(OUT, f)).size, 0);
console.log(`web-dist/ built: ${files.length + 1} files, ${(bytes / 1e6).toFixed(1)} MB, cache ${version}`);
